"""Parametric Structural BIM Reconstruction Engine.

Generates structural grids, reinforced concrete columns (rectangular and circular),
structural beams, isolated pad footings, strip footings, and structural slabs.

DISCLAIMER & ENGINEERING INTEGRITY BOUNDARY:
All structural elements, profiles, dimensions, and placements generated by this engine
are strictly spatial and geometrical modeling representations for architectural and BIM
coordination. They DO NOT constitute structural engineering calculations, load-bearing
verifications, or licensed professional structural designs. A licensed structural engineer
must independently calculate and approve all structural members before construction.
"""

import math
from dataclasses import dataclass, field
from typing import List, Tuple, Dict, Any, Optional, Set
from shapely.geometry import Polygon, LineString, Point, box


ENGINEERING_DISCLAIMER: str = (
    "NOTICE: Structural member geometry, cross-sections, and placements generated by this pipeline "
    "are spatial modeling representations for BIM coordination and visualization only. They DO NOT "
    "constitute structural calculations, load-bearing assessments, or licensed structural engineering design. "
    "All structural elements must be independently calculated, verified, and detailed by a licensed "
    "professional structural engineer before construction."
)


@dataclass
class StructuralGrid:
    id: str
    name: str
    start: Tuple[float, float]
    end: Tuple[float, float]
    orientation: str = "orthogonal"  # "orthogonal" or "rotated"
    provenance: str = "inferred"      # "detected", "configured", "inferred"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "name": self.name,
            "start": [round(self.start[0], 2), round(self.start[1], 2)],
            "end": [round(self.end[0], 2), round(self.end[1], 2)],
            "orientation": self.orientation,
            "provenance": self.provenance,
        }


@dataclass
class StructuralColumn:
    id: str
    name: str
    profile: str  # "rectangular" or "circular"
    width: float
    depth: float
    at: Tuple[float, float]
    level_id: str = "Level 1"
    top_level_id: str = "Level 2"
    height: float = 3000.0
    diameter: Optional[float] = None
    angle: float = 0.0
    base_offset: float = 0.0
    material: str = "Concrete"
    structural_role: str = "load_bearing"
    grid_intersection: Optional[str] = None
    source_entities: List[str] = field(default_factory=list)
    provenance: str = "inferred"
    confidence: str = "high"
    approval_status: str = "pending"

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {
            "id": self.id,
            "name": self.name,
            "profile": self.profile,
            "width": round(self.width, 2),
            "depth": round(self.depth, 2),
            "at": [round(self.at[0], 2), round(self.at[1], 2)],
            "angle": round(self.angle, 2),
            "levelId": self.level_id,
            "topLevelId": self.top_level_id,
            "height": round(self.height, 2),
            "baseOffset": round(self.base_offset, 2),
            "material": self.material,
            "structuralRole": self.structural_role,
            "sourceEntities": self.source_entities,
            "provenance": self.provenance,
            "confidence": self.confidence,
            "approvalStatus": self.approval_status,
        }
        if self.diameter is not None:
            d["diameter"] = round(self.diameter, 2)
        if self.grid_intersection:
            d["gridIntersection"] = self.grid_intersection
        return d


@dataclass
class StructuralBeam:
    id: str
    name: str
    width: float
    depth: float
    start: Tuple[float, float]
    end: Tuple[float, float]
    level_id: str = "Level 2"
    profile: str = "rectangular"
    start_column_id: Optional[str] = None
    end_column_id: Optional[str] = None
    offset: float = 0.0
    end_offset: float = 0.0
    material: str = "Concrete"
    beam_type: str = "primary"  # "primary" or "secondary"
    source_entities: List[str] = field(default_factory=list)
    provenance: str = "inferred"
    confidence: str = "high"
    approval_status: str = "pending"

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {
            "id": self.id,
            "name": self.name,
            "profile": self.profile,
            "width": round(self.width, 2),
            "depth": round(self.depth, 2),
            "start": [round(self.start[0], 2), round(self.start[1], 2)],
            "end": [round(self.end[0], 2), round(self.end[1], 2)],
            "levelId": self.level_id,
            "offset": round(self.offset, 2),
            "endOffset": round(self.end_offset, 2),
            "material": self.material,
            "beamType": self.beam_type,
            "sourceEntities": self.source_entities,
            "provenance": self.provenance,
            "confidence": self.confidence,
            "approvalStatus": self.approval_status,
        }
        if self.start_column_id:
            d["startColumnId"] = self.start_column_id
        if self.end_column_id:
            d["endColumnId"] = self.end_column_id
        return d


@dataclass
class StructuralFoundation:
    id: str
    name: str
    foundation_type: str  # "isolated" or "strip"
    width: float
    thickness: float
    level_id: str = "Level 1"
    depth: Optional[float] = None  # length for pad footings
    at: Optional[Tuple[float, float]] = None  # for isolated pad footings
    points: Optional[List[Tuple[float, float]]] = None  # for strip footings
    offset: float = -1200.0
    angle: float = 0.0
    supporting_element_id: Optional[str] = None
    material: str = "Concrete"
    provenance: str = "inferred"
    confidence: str = "high"
    approval_status: str = "pending"

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {
            "id": self.id,
            "name": self.name,
            "foundationType": self.foundation_type,
            "width": round(self.width, 2),
            "thickness": round(self.thickness, 2),
            "levelId": self.level_id,
            "offset": round(self.offset, 2),
            "angle": round(self.angle, 2),
            "material": self.material,
            "provenance": self.provenance,
            "confidence": self.confidence,
            "approvalStatus": self.approval_status,
        }
        if self.depth is not None:
            d["depth"] = round(self.depth, 2)
        if self.at is not None:
            d["at"] = [round(self.at[0], 2), round(self.at[1], 2)]
        if self.points is not None:
            d["points"] = [[round(p[0], 2), round(p[1], 2)] for p in self.points]
        if self.supporting_element_id:
            d["supportingElementId"] = self.supporting_element_id
        return d


@dataclass
class StructuralModel:
    grids: List[StructuralGrid] = field(default_factory=list)
    columns: List[StructuralColumn] = field(default_factory=list)
    beams: List[StructuralBeam] = field(default_factory=list)
    foundations: List[StructuralFoundation] = field(default_factory=list)
    engineering_disclaimer: str = ENGINEERING_DISCLAIMER

    def to_dict(self) -> Dict[str, Any]:
        return {
            "structuralGrids": [g.to_dict() for g in self.grids],
            "columns": [c.to_dict() for c in self.columns],
            "beams": [b.to_dict() for b in self.beams],
            "foundations": [f.to_dict() for f in self.foundations],
            "engineeringDisclaimer": self.engineering_disclaimer,
        }


class ParametricStructuralEngine:
    """Engine for generating structural grids, RC columns, RC beams, and foundations."""

    @classmethod
    def calculate_grid_intersections(
        cls,
        grids: List[StructuralGrid],
    ) -> Dict[Tuple[str, str], Tuple[Tuple[float, float], str]]:
        """Calculates 2D intersections between all pairs of grid lines.

        Returns dict mapping (grid1_id, grid2_id) -> ((x, y), label)
        e.g. ("grid_A", "grid_1") -> ((0.0, 0.0), "A-1")
        """
        intersections: Dict[Tuple[str, str], Tuple[Tuple[float, float], str]] = {}
        n = len(grids)
        for i in range(n):
            for j in range(i + 1, n):
                g1 = grids[i]
                g2 = grids[j]
                l1 = LineString([g1.start, g1.end])
                l2 = LineString([g2.start, g2.end])
                inter = l1.intersection(l2)
                if not inter.is_empty and inter.geom_type == "Point":
                    pt = (float(inter.x), float(inter.y))
                    # Formulate name e.g. "A-1" if g1 is letter and g2 is digit
                    n1, n2 = g1.name, g2.name
                    if n1.isalpha() and n2.isdigit():
                        lbl = f"{n1}-{n2}"
                    elif n2.isalpha() and n1.isdigit():
                        lbl = f"{n2}-{n1}"
                    else:
                        lbl = f"{n1}-{n2}"
                    intersections[(g1.id, g2.id)] = (pt, lbl)
                    intersections[(g2.id, g1.id)] = (pt, lbl)
        return intersections

    @classmethod
    def find_nearest_grid_intersection(
        cls,
        pt: Tuple[float, float],
        grid_intersections: Dict[Tuple[str, str], Tuple[Tuple[float, float], str]],
        tolerance: float = 200.0,
    ) -> Optional[str]:
        """Finds closest grid intersection tag if within tolerance."""
        min_dist = float("inf")
        best_label: Optional[str] = None
        seen_labels: Set[str] = set()

        for (pt_inter, lbl) in grid_intersections.values():
            if lbl in seen_labels:
                continue
            seen_labels.add(lbl)
            dist = math.hypot(pt[0] - pt_inter[0], pt[1] - pt_inter[1])
            if dist < min_dist and dist <= tolerance:
                min_dist = dist
                best_label = lbl
        return best_label

    @classmethod
    def generate_orthogonal_grids_from_bounds(
        cls,
        x_coords: List[float],
        y_coords: List[float],
        margin: float = 1500.0,
        cluster_tol: float = 100.0,
        rotation_angle_deg: float = 0.0,
    ) -> List[StructuralGrid]:
        """Generates named structural grid lines from significant X and Y coordinates.

        Vertical lines (running in Y direction) are numbered 1, 2, 3...
        Horizontal lines (running in X direction) are lettered A, B, C...
        """
        # Cluster coordinates within tolerance
        def cluster_1d(coords: List[float]) -> List[float]:
            if not coords:
                return []
            sorted_c = sorted(coords)
            clusters: List[List[float]] = [[sorted_c[0]]]
            for c in sorted_c[1:]:
                if abs(c - clusters[-1][-1]) <= cluster_tol:
                    clusters[-1].append(c)
                else:
                    clusters.append([c])
            return [sum(cl) / len(cl) for cl in clusters]

        unique_x = cluster_1d(x_coords)
        unique_y = cluster_1d(y_coords)

        if not unique_x or not unique_y:
            return []

        min_x, max_x = min(unique_x), max(unique_x)
        min_y, max_y = min(unique_y), max(unique_y)

        # Extend grid lines by margin
        x_start_y = min_y - margin
        x_end_y = max_y + margin
        y_start_x = min_x - margin
        y_end_x = max_x + margin

        grids: List[StructuralGrid] = []

        # Vertical grid lines (constant X) -> Numbered 1, 2, 3...
        for idx, x in enumerate(unique_x, start=1):
            name = str(idx)
            gid = f"grid_{name}"
            start_pt = (x, x_start_y)
            end_pt = (x, x_end_y)

            if abs(rotation_angle_deg) > 1e-4:
                # Rotate points around center if model is rotated
                cx, cy = (min_x + max_x) / 2.0, (min_y + max_y) / 2.0
                rad = math.radians(rotation_angle_deg)
                cos_a, sin_a = math.cos(rad), math.sin(rad)
                p1_rot = (
                    cx + (start_pt[0] - cx) * cos_a - (start_pt[1] - cy) * sin_a,
                    cy + (start_pt[0] - cx) * sin_a + (start_pt[1] - cy) * cos_a,
                )
                p2_rot = (
                    cx + (end_pt[0] - cx) * cos_a - (end_pt[1] - cy) * sin_a,
                    cy + (end_pt[0] - cx) * sin_a + (end_pt[1] - cy) * cos_a,
                )
                grids.append(StructuralGrid(
                    id=gid,
                    name=name,
                    start=p1_rot,
                    end=p2_rot,
                    orientation="rotated",
                    provenance="inferred",
                ))
            else:
                grids.append(StructuralGrid(
                    id=gid,
                    name=name,
                    start=start_pt,
                    end=end_pt,
                    orientation="orthogonal",
                    provenance="inferred",
                ))

        # Horizontal grid lines (constant Y) -> Lettered A, B, C...
        for idx, y in enumerate(unique_y):
            # A, B, C... (or AA, BB if > 26)
            name = chr(ord('A') + idx) if idx < 26 else f"A{idx}"
            gid = f"grid_{name}"
            start_pt = (y_start_x, y)
            end_pt = (y_end_x, y)

            if abs(rotation_angle_deg) > 1e-4:
                cx, cy = (min_x + max_x) / 2.0, (min_y + max_y) / 2.0
                rad = math.radians(rotation_angle_deg)
                cos_a, sin_a = math.cos(rad), math.sin(rad)
                p1_rot = (
                    cx + (start_pt[0] - cx) * cos_a - (start_pt[1] - cy) * sin_a,
                    cy + (start_pt[0] - cx) * sin_a + (start_pt[1] - cy) * cos_a,
                )
                p2_rot = (
                    cx + (end_pt[0] - cx) * cos_a - (end_pt[1] - cy) * sin_a,
                    cy + (end_pt[0] - cx) * sin_a + (end_pt[1] - cy) * cos_a,
                )
                grids.append(StructuralGrid(
                    id=gid,
                    name=name,
                    start=p1_rot,
                    end=p2_rot,
                    orientation="rotated",
                    provenance="inferred",
                ))
            else:
                grids.append(StructuralGrid(
                    id=gid,
                    name=name,
                    start=start_pt,
                    end=end_pt,
                    orientation="orthogonal",
                    provenance="inferred",
                ))

        return grids

    @classmethod
    def generate_columns_at_locations(
        cls,
        locations: List[Tuple[float, float]],
        levels: List[Dict[str, Any]],
        width: float = 300.0,
        depth: float = 300.0,
        profile: str = "rectangular",
        diameter: Optional[float] = None,
        angle: float = 0.0,
        grid_intersections: Optional[Dict[Tuple[str, str], Tuple[Tuple[float, float], str]]] = None,
        material: str = "Concrete",
        provenance: str = "inferred",
        source_entities: Optional[List[str]] = None,
    ) -> List[StructuralColumn]:
        """Generates structural columns at target locations across all inhabited storeys."""
        if width < 100.0 or depth < 100.0:
            raise ValueError(f"Column dimensions ({width}x{depth}) must be at least 100 mm.")

        inhabited_levels = [l for l in levels if l.get("storeyType") != "roof_datum"]
        if not inhabited_levels:
            inhabited_levels = levels[:1]

        columns: List[StructuralColumn] = []
        col_idx = 1

        for pt in locations:
            inter_tag = None
            if grid_intersections:
                inter_tag = cls.find_nearest_grid_intersection(pt, grid_intersections)

            # Create column per storey
            for s_idx, lvl in enumerate(inhabited_levels):
                lvl_id = lvl.get("name", f"Level {s_idx + 1}")
                # Top level is next level if available
                if s_idx + 1 < len(levels):
                    top_lvl_id = levels[s_idx + 1].get("name", f"Level {s_idx + 2}")
                else:
                    top_lvl_id = f"Level {s_idx + 2}"

                h = float(lvl.get("height", 3000.0))
                cid = f"col_{col_idx}" if len(inhabited_levels) == 1 else f"col_{col_idx}_L{s_idx + 1}"
                name = f"C{col_idx}" if len(inhabited_levels) == 1 else f"C{col_idx}-L{s_idx + 1}"

                col = StructuralColumn(
                    id=cid,
                    name=name,
                    profile=profile,
                    width=width,
                    depth=depth,
                    at=pt,
                    diameter=diameter if profile == "circular" else None,
                    angle=angle,
                    level_id=lvl_id,
                    top_level_id=top_lvl_id,
                    height=h,
                    material=material,
                    grid_intersection=inter_tag,
                    source_entities=list(source_entities or []),
                    provenance=provenance,
                    confidence="high",
                    approval_status="pending",
                )
                columns.append(col)

            col_idx += 1

        return columns

    @classmethod
    def generate_beams_between_columns(
        cls,
        columns: List[StructuralColumn],
        levels: List[Dict[str, Any]],
        width: float = 230.0,
        depth: float = 450.0,
        max_span: float = 12000.0,
        min_span: float = 1000.0,
        material: str = "Concrete",
        provenance: str = "inferred",
    ) -> List[StructuralBeam]:
        """Generates primary structural beams connecting adjacent column centers at floor levels."""
        if width < 100.0 or depth < 100.0:
            raise ValueError(f"Beam dimensions ({width}x{depth}) must be at least 100 mm.")

        # Group columns by top_level_id (the floor level at which the beams will be placed)
        level_cols: Dict[str, List[StructuralColumn]] = {}
        for c in columns:
            tl = c.top_level_id
            if tl not in level_cols:
                level_cols[tl] = []
            level_cols[tl].append(c)

        beams: List[StructuralBeam] = []
        beam_idx = 1

        for lvl_name, cols in level_cols.items():
            n = len(cols)
            added_pairs: Set[Tuple[str, str]] = set()

            for i in range(n):
                c1 = cols[i]
                for j in range(i + 1, n):
                    c2 = cols[j]
                    pair_key = (min(c1.id, c2.id), max(c1.id, c2.id))
                    if pair_key in added_pairs:
                        continue

                    # Calculate distance
                    dx = c2.at[0] - c1.at[0]
                    dy = c2.at[1] - c1.at[1]
                    dist = math.hypot(dx, dy)

                    if min_span <= dist <= max_span:
                        # Check alignment: must be orthogonal or share a grid line axis
                        angle_deg = math.degrees(math.atan2(abs(dy), abs(dx)))
                        is_orthogonal = (angle_deg < 5.0) or (abs(angle_deg - 90.0) < 5.0)

                        shares_grid = False
                        if c1.grid_intersection and c2.grid_intersection:
                            c1_parts = c1.grid_intersection.split("-")
                            c2_parts = c2.grid_intersection.split("-")
                            shares_grid = any(p in c2_parts for p in c1_parts)

                        if is_orthogonal or shares_grid:
                            bid = f"beam_{beam_idx}"
                            name = f"B{beam_idx}"
                            beam = StructuralBeam(
                                id=bid,
                                name=name,
                                width=width,
                                depth=depth,
                                start=c1.at,
                                end=c2.at,
                                level_id=lvl_name,
                                start_column_id=c1.id,
                                end_column_id=c2.id,
                                material=material,
                                beam_type="primary",
                                provenance=provenance,
                                confidence="high",
                                approval_status="pending",
                            )
                            beams.append(beam)
                            added_pairs.add(pair_key)
                            beam_idx += 1

        return beams

    @classmethod
    def generate_foundations(
        cls,
        columns: List[StructuralColumn],
        walls: List[Any],
        foundation_type: str = "isolated",  # "isolated", "strip", or "both"
        pad_width: float = 1200.0,
        pad_depth: float = 1200.0,
        pad_thickness: float = 400.0,
        pad_offset: float = -1200.0,
        strip_width: float = 600.0,
        strip_thickness: float = 300.0,
        strip_offset: float = -600.0,
        level_id: str = "Level 1",
        material: str = "Concrete",
        provenance: str = "inferred",
    ) -> List[StructuralFoundation]:
        """Generates isolated pad footings beneath ground columns and/or strip footings under exterior walls."""
        foundations: List[StructuralFoundation] = []
        f_idx = 1

        # 1. Isolated Pad Footings beneath ground columns
        if foundation_type in ("isolated", "both"):
            ground_cols = [c for c in columns if c.level_id in ("Level 1", "level_1")]
            for col in ground_cols:
                fid = f"ftg_{f_idx}"
                name = f"F{f_idx}"
                f = StructuralFoundation(
                    id=fid,
                    name=name,
                    foundation_type="isolated",
                    width=pad_width,
                    depth=pad_depth,
                    thickness=pad_thickness,
                    offset=pad_offset,
                    at=col.at,
                    angle=col.angle,
                    level_id=level_id,
                    supporting_element_id=col.id,
                    material=material,
                    provenance=provenance,
                    confidence="high",
                    approval_status="pending",
                )
                foundations.append(f)
                f_idx += 1

        # 2. Strip Footings beneath exterior/load-bearing walls
        if foundation_type in ("strip", "both"):
            for w in walls:
                w_class = getattr(w, "classification", "") if hasattr(w, "classification") else w.get("classification", "")
                w_id = getattr(w, "id", "") if hasattr(w, "id") else w.get("id", "")
                w_lvl = getattr(w, "level_id", "Level 1") if hasattr(w, "level_id") else w.get("levelId", "Level 1")
                w_start = getattr(w, "start", [0, 0]) if hasattr(w, "start") else w.get("start", [0, 0])
                w_end = getattr(w, "end", [0, 0]) if hasattr(w, "end") else w.get("end", [0, 0])

                if w_lvl in ("Level 1", "level_1"):
                    fid = f"strip_ftg_{f_idx}"
                    name = f"SF{f_idx}"
                    f = StructuralFoundation(
                        id=fid,
                        name=name,
                        foundation_type="strip",
                        width=strip_width,
                        thickness=strip_thickness,
                        offset=strip_offset,
                        points=[(float(w_start[0]), float(w_start[1])), (float(w_end[0]), float(w_end[1]))],
                        level_id=level_id,
                        supporting_element_id=str(w_id),
                        material=material,
                        provenance=provenance,
                        confidence="high",
                        approval_status="pending",
                    )
                    foundations.append(f)
                    f_idx += 1

        return foundations

    @classmethod
    def classify_structural_slabs(
        cls,
        floors: List[Dict[str, Any]],
        levels: List[Dict[str, Any]],
    ) -> List[Dict[str, Any]]:
        """Classifies slabs as 'ground_bearing', 'structural', or 'roof_slab' while preserving openings."""
        updated_floors: List[Dict[str, Any]] = []
        inhabited = [l for l in levels if l.get("storeyType") != "roof_datum"]
        top_inhabited_name = inhabited[-1].get("name", "Level 1") if inhabited else "Level 1"

        for fl in floors:
            fl_copy = dict(fl)
            lvl = fl_copy.get("levelId", "Level 1")
            elev = fl_copy.get("elevation", 0.0)

            if lvl in ("Level 1", "level_1") and abs(elev) < 1e-3:
                fl_copy["structuralRole"] = "ground_bearing"
            elif lvl == top_inhabited_name and len(inhabited) > 1:
                fl_copy["structuralRole"] = "roof_slab"
            else:
                fl_copy["structuralRole"] = "structural"

            updated_floors.append(fl_copy)

        return updated_floors
